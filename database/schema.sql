-- TemuToko Marketplace COD - MySQL 8+ / MariaDB (XAMPP)
CREATE DATABASE IF NOT EXISTS marketplace_cod CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE marketplace_cod;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 role ENUM('super_admin','admin_toko','customer') NOT NULL,
 name VARCHAR(120) NOT NULL, email VARCHAR(191) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,phone VARCHAR(32),
 status ENUM('active','suspended','deleted') NOT NULL DEFAULT 'active',
 last_login_at DATETIME NULL,deleted_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_users_role_status(role,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS password_resets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,expires_at DATETIME NOT NULL,used_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stores (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,owner_user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,slug VARCHAR(191) NOT NULL UNIQUE,description TEXT,logo_url VARCHAR(500),
 city VARCHAR(100) NOT NULL,address VARCHAR(255) NOT NULL,cod_area_note VARCHAR(255),phone VARCHAR(32) NOT NULL,
 status ENUM('pending','approved','rejected','suspended') NOT NULL DEFAULT 'pending',
 rejection_reason TEXT,verified_by BIGINT UNSIGNED NULL,verified_at DATETIME NULL,last_active_at DATETIME NULL,deleted_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(owner_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(verified_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_stores_status_city(status,city),INDEX idx_stores_activity(last_active_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,parent_id BIGINT UNSIGNED NULL,
 name VARCHAR(120) NOT NULL,slug VARCHAR(150) NOT NULL UNIQUE,icon VARCHAR(100),sort_order INT NOT NULL DEFAULT 0,is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(parent_id) REFERENCES categories(id) ON DELETE RESTRICT,INDEX idx_categories_parent(parent_id,is_active)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,store_id BIGINT UNSIGNED NOT NULL,category_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(200) NOT NULL,slug VARCHAR(210) NOT NULL UNIQUE,description TEXT,
 price DECIMAL(12,2) NOT NULL,compare_price DECIMAL(12,2) NULL,sku VARCHAR(100),
 stock INT UNSIGNED NOT NULL DEFAULT 0,reserved INT UNSIGNED NOT NULL DEFAULT 0,low_stock_threshold INT UNSIGNED NOT NULL DEFAULT 5,
 status ENUM('active','draft','archived') NOT NULL DEFAULT 'active',sold_count INT UNSIGNED NOT NULL DEFAULT 0,
 rating_avg DECIMAL(3,2) NOT NULL DEFAULT 0,rating_count INT UNSIGNED NOT NULL DEFAULT 0,deleted_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(store_id) REFERENCES stores(id) ON DELETE RESTRICT,FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE RESTRICT,
 INDEX idx_products_store_status(store_id,status),INDEX idx_products_category(category_id,status),INDEX idx_products_price(price),INDEX idx_products_sold(sold_count),
 FULLTEXT INDEX idx_products_search(name,description),CONSTRAINT chk_product_stock CHECK(stock>=reserved),CONSTRAINT chk_product_price CHECK(price>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,product_id BIGINT UNSIGNED NOT NULL,url VARCHAR(500) NOT NULL,sort_order INT NOT NULL DEFAULT 0,is_primary BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT,INDEX idx_images_product(product_id,sort_order)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS uploaded_files (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,filename VARCHAR(191) NOT NULL UNIQUE,mime VARCHAR(100) NOT NULL,data MEDIUMBLOB NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,code VARCHAR(40) UNIQUE,
 customer_id BIGINT UNSIGNED NOT NULL,store_id BIGINT UNSIGNED NOT NULL,
 status ENUM('pending','confirmed','paid','completed','cancelled') NOT NULL DEFAULT 'pending',
 subtotal DECIMAL(12,2) NOT NULL,total DECIMAL(12,2) NOT NULL,
 payment_method ENUM('cod_cash') NOT NULL DEFAULT 'cod_cash',meeting_location VARCHAR(255),meeting_at DATETIME,
 customer_note TEXT,cancel_reason TEXT,confirmed_at DATETIME,paid_at DATETIME,completed_at DATETIME,cancelled_at DATETIME,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT,FOREIGN KEY(store_id) REFERENCES stores(id) ON DELETE RESTRICT,
 INDEX idx_orders_store_status_date(store_id,status,created_at),INDEX idx_orders_customer_date(customer_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,order_id BIGINT UNSIGNED NOT NULL,product_id BIGINT UNSIGNED NOT NULL,
 product_name VARCHAR(200) NOT NULL,unit_price DECIMAL(12,2) NOT NULL,qty INT UNSIGNED NOT NULL,line_total DECIMAL(12,2) NOT NULL,image_url VARCHAR(500),
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT,
 INDEX idx_order_items_order(order_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,product_id BIGINT UNSIGNED NOT NULL,store_id BIGINT UNSIGNED NOT NULL,
 type ENUM('masuk','kurang','koreksi','penjualan','batal') NOT NULL,qty INT NOT NULL,balance_after INT UNSIGNED NOT NULL,note VARCHAR(255),
 order_id BIGINT UNSIGNED NULL,created_by BIGINT UNSIGNED NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT,FOREIGN KEY(store_id) REFERENCES stores(id) ON DELETE RESTRICT,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_stock_movements_product_date(product_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cart_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,product_id BIGINT UNSIGNED NOT NULL,qty INT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,UNIQUE KEY uniq_cart(user_id,product_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_status_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,order_id BIGINT UNSIGNED NOT NULL,from_status VARCHAR(25),to_status VARCHAR(25) NOT NULL,
 actor_user_id BIGINT UNSIGNED NULL,note TEXT,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,FOREIGN KEY(actor_user_id) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_history_order(order_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chat_threads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,store_id BIGINT UNSIGNED NOT NULL,customer_id BIGINT UNSIGNED NOT NULL,
 last_message_at DATETIME,store_unread INT UNSIGNED NOT NULL DEFAULT 0,customer_unread INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,UNIQUE KEY uniq_thread(store_id,customer_id),
 FOREIGN KEY(store_id) REFERENCES stores(id) ON DELETE RESTRICT,FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chat_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,thread_id BIGINT UNSIGNED NOT NULL,sender_id BIGINT UNSIGNED NULL,order_id BIGINT UNSIGNED NULL,
 type ENUM('text','product','system') NOT NULL DEFAULT 'text',body VARCHAR(1000) NOT NULL,read_at DATETIME,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(thread_id) REFERENCES chat_threads(id) ON DELETE RESTRICT,
 FOREIGN KEY(sender_id) REFERENCES users(id) ON DELETE SET NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,INDEX idx_messages_thread(thread_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS finance_transactions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,store_id BIGINT UNSIGNED NOT NULL,
 type ENUM('income','expense') NOT NULL,category VARCHAR(100) NOT NULL,amount DECIMAL(12,2) NOT NULL,
 description VARCHAR(500),trx_date DATE NOT NULL,order_id BIGINT UNSIGNED NULL UNIQUE,
 created_by BIGINT UNSIGNED NULL,deleted_at DATETIME NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(store_id) REFERENCES stores(id) ON DELETE RESTRICT,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_finance_store_date(store_id,trx_date,type),CONSTRAINT chk_finance_amount CHECK(amount>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,product_id BIGINT UNSIGNED NOT NULL,
 order_id BIGINT UNSIGNED NOT NULL,customer_id BIGINT UNSIGNED NOT NULL,
 rating TINYINT UNSIGNED NOT NULL,comment TEXT,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uniq_review(order_id,product_id),
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT chk_review_rating CHECK(rating BETWEEN 1 AND 5)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS wishlists (
 user_id BIGINT UNSIGNED NOT NULL,product_id BIGINT UNSIGNED NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,product_id),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 type VARCHAR(40) NOT NULL,title VARCHAR(200) NOT NULL,body TEXT,link VARCHAR(255),is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,INDEX idx_notification_unread(user_id,is_read,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS banners (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,title VARCHAR(200) NOT NULL,subtitle VARCHAR(500),cta_label VARCHAR(100),cta_link VARCHAR(255),image_url VARCHAR(500),
 placement ENUM('hero','promo') NOT NULL DEFAULT 'hero',sort_order INT NOT NULL DEFAULT 0,is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,actor_user_id BIGINT UNSIGNED NULL,action VARCHAR(100) NOT NULL,target_type VARCHAR(100) NOT NULL,target_id BIGINT UNSIGNED,
 meta JSON,ip_address VARCHAR(48),created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_user_id) REFERENCES users(id) ON DELETE SET NULL,INDEX idx_audit_date(action,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 `key` VARCHAR(100) PRIMARY KEY,`value` VARCHAR(500) NOT NULL
) ENGINE=InnoDB;
